/* 經緯度格子的雜湊(0~1)—— 同一個地方永遠同一個值 */
function hash(ix, iy){
  let h = (ix * 374761393 + iy * 668265263) | 0;
  h = (h ^ (h >>> 13)) * 1274126177 | 0;
  return ((h ^ (h >>> 16)) >>> 0) / 4294967295;
}
/* 平滑一點的雜訊:四個格點雙線性內插(格子 2 度)—— 森林、草地是一片一片的,不是灑鹽 */
function noise(lng, lat, cell){
  const x = lng / cell, y = lat / cell, x0 = Math.floor(x), y0 = Math.floor(y), fx = x - x0, fy = y - y0;
  const a = hash(x0, y0), b = hash(x0 + 1, y0), c = hash(x0, y0 + 1), d = hash(x0 + 1, y0 + 1);
  return (a * (1 - fx) + b * fx) * (1 - fy) + (c * (1 - fx) + d * fx) * fy;
}
function desertAt(lng, lat){
  let best = -1;                       // ⚠ 沙漠外面要是負的:從 0 起算的話,整片大陸都會落在「沙漠邊緣 = 莽原」
  for(const [cx, cy, rx, ry] of TR.DESERTS){
    let dx = lng - cx; dx -= Math.round(dx / 360) * 360;
    const v = 1 - ((dx / rx) ** 2 + ((lat - cy) / ry) ** 2);
    if(v > best) best = v;
  }
  return Math.max(-1, best);
}
/* 一個陸地像素的顏色 */
function biome(lng, lat){
  const a = Math.abs(lat);
  const n = noise(lng, lat, 2), n2 = hash(Math.floor(lng * 3), Math.floor(lat * 3));
  // 高緯度用平滑的大雜訊(格子 6 度):靠近極點經度被拉得很寬,細雜訊會變成一條條的怪花紋
  const nb = noise(lng, lat, 6);
  if(a > 74 || (a > 66 && nb > .5)) return MP.snow;
  if(a > 60) return nb < .55 ? MP.tundra : MP.forest2;
  // 沙漠邊緣用細一點的雜訊打散,不然是一顆顆完美的橢圓
  const d = desertAt(lng, lat) + (noise(lng, lat, .7) - .5) * .8 + (n - .5) * .3;
  if(d > .15) return n2 < .7 ? MP.sand : MP.sand2;
  if(d > -.12) return MP.savanna;
  if(a < 9) return n < .62 ? MP.forest : MP.forest2;
  if(a < 20) return n < .45 ? MP.savanna : n < .75 ? MP.grass : MP.forest;
  if(a > 48) return n < .55 ? MP.forest2 : MP.forest;
  return n < .5 ? MP.grass : n < .78 ? MP.grass2 : MP.forest;
}
TR.biome = biome;

