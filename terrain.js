/* 投影:P = { lo0, lo1, la0, la1, global }。整球的時候經度要環繞 */
function X(P, W, lng){
  if(!P.global){ const mid = (P.lo0 + P.lo1) / 2; lng -= Math.round((lng - mid) / 360) * 360; }
  return (lng - P.lo0) / (P.lo1 - P.lo0) * W;
}
const Y = (P, H, lat) => (P.la1 - lat) / (P.la1 - P.la0) * H;
function polyline(c, pts, P, W, H){
  c.beginPath();
  pts.forEach(([lng, lat], i) => { const x = X(P, W, lng), y = Y(P, H, lat); i ? c.lineTo(x, y) : c.moveTo(x, y); });
}
function inView(pts, P){
  if(P.global) return true;
  const pad = 3;
  return pts.some(([lng, lat]) => { const mid = (P.lo0 + P.lo1) / 2; lng -= Math.round((lng - mid) / 360) * 360;
    return lng > P.lo0 - pad && lng < P.lo1 + pad && lat > P.la0 - pad && lat < P.la1 + pad; });
}

